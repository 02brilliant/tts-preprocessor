def main() -> int:
    failures: list[str] = []
    for source, expected in CASES:
        actual = transform(source)
        if actual != expected:
            failures.append(f"{source!r}: expected {expected!r}, got {actual!r}")
    for source in ("1:02:03", "1:2:3:4:5:6:7:8:9", "01:2:3"):
        actual = transform(f"{source} 옆 25℃")
        if source not in actual or "이십오도" not in actual:
            failures.append(f"neighbor failed for {source!r}: got {actual!r}")
    if failures:
        print("\n".join(failures))
        return 1
    print("OK: no numeric-delimited multi-colon failures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
