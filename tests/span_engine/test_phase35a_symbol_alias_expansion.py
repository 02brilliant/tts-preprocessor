from __future__ import annotations

import pytest

from engine.span_engine import transform


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("1／3", "삼분의 일"),
        ("1⁄3", "삼분의 일"),
        ("1∕3", "삼분의 일"),
        ("33.3％", "삼십삼쩜삼 퍼센트"),
        ("2.5％p", "이쩜오 퍼센트포인트"),
        ("33.3﹪", "삼십삼쩜삼 퍼센트"),
        ("2.5﹪p", "이쩜오 퍼센트포인트"),
        ("2.5％pa", "2.5％pa"),
        ("13：05에 시작", "십삼시 오분에 시작"),
        ("3∼8cm", "삼에서 팔 센티미터"),
        ("3～8cm", "삼에서 팔 센티미터"),
        ("3〜8cm", "삼에서 팔 센티미터"),
        ("1∼11월", "일월에서 십일월"),
        ("1～11월", "일월에서 십일월"),
        ("1〜11월", "일월에서 십일월"),
        ("−2.5℃", "영하 이쩜오도"),
        ("－2.5℉", "화씨 영하 이쩜오도"),
        ("−2.5%p", "마이너스 이쩜오 퍼센트포인트"),
        ("−1/3", "마이너스 삼분의 일"),
        ("25°C", "이십오도"),
        ("25° C", "이십오도"),
        ("25º C", "이십오도"),
        ("25°F", "화씨 이십오도"),
        ("25° F", "화씨 이십오도"),
        ("25º F", "화씨 이십오도"),
        ("-2.5°F", "화씨 영하 이쩜오도"),
        ("45㎠", "사십오 제곱센티미터"),
        ("45㎢", "사십오 제곱킬로미터"),
        ("45㎤", "사십오 세제곱센티미터"),
        ("45㎦", "사십오 세제곱킬로미터"),
        ("5㎝", "오 센티미터"),
        ("5㎜", "오 밀리미터"),
        ("3㎏", "삼 킬로그램"),
        ("5㎎", "오 밀리그램"),
        ("60㎐", "육십 헤르츠"),
        ("3.2㎒", "삼쩜이 메가헤르츠"),
        ("3.2㎓", "삼쩜이 기가헤르츠"),
        ("90km／h", "시속 구십 킬로미터"),
        ("90㎞／h", "시속 구십 킬로미터"),
        ("5m／s", "초속 오 미터"),
        ("5cm／s", "초속 오 센티미터"),
        ("15.2km／L", "리터당 십오쩜이 킬로미터"),
        ("15.2㎞／ℓ", "리터당 십오쩜이 킬로미터"),
        ("5mg／dL", "데시리터당 오 밀리그램"),
        ("3GB／s", "초당 삼 기가바이트"),
        ("＄25.99", "이십오쩜구구 달러"),
        ("﹩25.99", "이십오쩜구구 달러"),
        ("¥1,500", "천오백 엔"),
        ("￥1,500", "천오백 엔"),
    ],
)
def test_phase35a_owner_local_symbol_alias_expansion(
    text: str, expected: str
) -> None:
    assert transform(text) == expected


@pytest.mark.parametrize(
    "text",
    [
        "https://example.com/a／b",
        '{"path":"a／b"}',
        "curl -X POST http://x/y",
        "The fraction is 1／3.",
        "The value is 2.5％p.",
    ],
)
def test_phase35a_alias_preserve_priority_for_non_korean_context(text: str) -> None:
    assert transform(text) == text
